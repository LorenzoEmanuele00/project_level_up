import 'package:levelup/domain/models.dart';
import 'package:levelup/domain/results.dart';

/// Produces a new unique identifier (a UUID in production).
typedef IdGenerator = String Function();

/// Thrown when a write refers to an entity that does not exist.
class EntityNotFoundException implements Exception {
  const EntityNotFoundException(this.entity, this.id);

  /// What was looked up, for example `habit`.
  final String entity;
  final String id;

  @override
  String toString() => 'EntityNotFoundException: no $entity with id "$id"';
}

/// Thrown when redeeming a reward that was already redeemed.
class RewardAlreadyRedeemedException implements Exception {
  const RewardAlreadyRedeemedException(this.rewardId);

  final String rewardId;

  @override
  String toString() =>
      'RewardAlreadyRedeemedException: reward "$rewardId" was already redeemed';
}

/// Everything the game reads and writes, independent of where it is stored.
///
/// The clock is always a parameter (`now`); ids are generated by the
/// repository. Instants come back as UTC with millisecond precision.
/// Time ranges are `from` inclusive, `to` exclusive. Heroes and habits are
/// ordered by creation instant, then id; completions by instant, then id.
///
/// Streams emit the current value on listen and again after each change.
/// Operations that touch several entities are atomic: they either write
/// everything or nothing.
abstract interface class GameRepository {
  /// The hero, or null before one exists (the earliest created, then by id,
  /// if there are several).
  Stream<GameHero?> watchHero();

  /// All habits; archived ones only with [includeArchived].
  Stream<List<Habit>> watchHabits({bool includeArchived = false});

  /// Completions of every habit in [from, to).
  Stream<List<Completion>> watchCompletionsBetween(DateTime from, DateTime to);

  /// Completions of every habit made on the local calendar day of [day].
  Stream<List<Completion>> watchCompletionsOn(DateTime day);

  /// Completions of one habit in [from, to).
  Future<List<Completion>> completionsBetween(
    String habitId,
    DateTime from,
    DateTime to,
  );

  /// Creates a level 1 hero with no EXP and no reward points.
  Future<GameHero> createHero({
    required AvatarMode avatarMode,
    required AccentKey accent,
    required ThemeKey theme,
    required DateTime now,
    String? userId,
    String? name,
    String? avatarIcon,
    HeroClass? heroClass,
  });

  /// Creates a habit of [heroId] with an empty history and `createdAt: now`.
  /// Throws [EntityNotFoundException] for an unknown hero.
  Future<Habit> createHabit({
    required String heroId,
    required String name,
    required String icon,
    required Difficulty difficulty,
    required Frequency frequency,
    required HabitHue hue,
    required DateTime now,
  });

  /// Creates a reward of [heroId]. Throws [EntityNotFoundException] for an
  /// unknown hero.
  Future<Reward> createReward({
    required String heroId,
    required String name,
    required RewardTier tier,
    required DateTime now,
    String? note,
  });

  /// Marks a habit as archived. Throws [EntityNotFoundException] for an
  /// unknown habit.
  Future<void> archiveHabit(String habitId, DateTime now);

  /// Completes a habit with the game rules and saves hero, habit and
  /// completion together. The rules see the habit's completions from the
  /// start of the previous week to the end of the local day of [now], so a
  /// completion recorded later the same day (clock set back) still counts as
  /// "already done". Negative outcomes (already done today, archived)
  /// write nothing. Throws [EntityNotFoundException] for an unknown habit.
  Future<CompletionResult> completeHabit(String habitId, DateTime now);

  /// Redeems a reward: pays the cost, records the redemption and marks the
  /// reward as redeemed (it is kept), together. Not enough points writes
  /// nothing. Throws [EntityNotFoundException] for an unknown reward and
  /// [RewardAlreadyRedeemedException] for one already redeemed; neither
  /// writes anything.
  Future<RedeemResult> redeemReward(String rewardId, DateTime now);
}
